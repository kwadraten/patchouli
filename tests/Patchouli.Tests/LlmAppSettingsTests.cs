            .WithProvider(new LlmProviderAppSettings("future-provider", "Future", "https://future.example", "m"))
            .WithoutProvider("DEEPSEEK");

        settings.FindProvider("deepseek").Should().BeNull();
        settings.FindProvider("future-provider")!.Model.Should().Be("m");
    }

