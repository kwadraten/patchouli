    [Fact]
    public void Resolve_base_url_does_not_double_a_versioned_snapshot_endpoint()
    {
        LlmProviderCatalogEntry deepseek = LlmProviderCatalog.Find("deepseek")!;
        LlmProviderCatalogEntry zai = LlmProviderCatalog.Find("zai")!;
        LlmProviderCatalogEntry upstage = LlmProviderCatalog.Find("upstage")!;

        deepseek.DefaultBaseUrl.Should().Be("https://api.deepseek.com");
        LlmProviderClientFactory.ResolveBaseUrl(deepseek, "", "", "")
            .Should().Be("https://api.deepseek.com/{0}/{1}");
        LlmProviderClientFactory.ResolveBaseUrl(zai, "", "", "")
            .Should().Be("https://api.z.ai/api/paas/v4/{1}");
        LlmProviderClientFactory.ResolveBaseUrl(upstage, "", "", "")
            .Should().Be("https://api.upstage.ai/v1/solar/{1}");
        LlmProviderClientFactory.ResolveBaseUrl(deepseek, "https://v2.example.test", "", "")
            .Should().Be("https://v2.example.test/{0}/{1}",
                "a version-looking hostname is not an API version segment");
        LlmProviderClientFactory.ResolveBaseUrl(deepseek, "https://host.example/v1beta", "", "")
            .Should().Be("https://host.example/v1beta/{1}");
    }

