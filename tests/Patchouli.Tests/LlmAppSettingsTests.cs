    [Fact]
    public async Task Inspect_reports_readiness_per_provider_without_secrets()
    {
        LlmProviderAppSettings deepseek = new("deepseek", "", "", "deepseek-chat");
        LlmProviderAppSettings azure = new("azure-openai", "Azure OpenAI", "", "gpt-4o", "res", "dep");
        LlmProviderAppSettings cohere = new("cohere", "Cohere", "https://api.cohere.com", "command");
        LlmAppSettings settings = LlmAppSettings.Default()
            .WithProvider(deepseek).WithProvider(azure).WithProvider(cohere);
        StubCredentialStore store = new() { Secret = "key" };

        IReadOnlyList<LlmProviderReadiness> readiness =
            await LlmProviderClientFactory.InspectAsync(settings, store);

        LlmProviderReadiness ById(string providerId)
        {
            return readiness.Single(item => item.ProviderId == providerId);
        }

        readiness.Should().HaveCount(LlmProviderCatalog.All.Count + LlmProviderCatalog.FallbackAll.Count);
        ById("deepseek").IsConfigured.Should().BeTrue();
        ById("deepseek").HasCredential.Should().BeTrue();
        ById("deepseek").Diagnostic.Should().Be("Ready.");
        ById("openai").Diagnostic.Should().Contain("base URL");
        ById("azure-openai").IsConfigured.Should().BeTrue();
        ById("cohere").IsConfigured.Should().BeFalse();
        ById("cohere").Diagnostic.Should().Contain("unsupported protocol").And.Contain("unknown");
        readiness.Select(item => item.Diagnostic)
            .Should().NotContain(text => text.Contains("sk-", StringComparison.Ordinal));
    }

    [Fact]
    public async Task Inspect_marks_a_keyed_provider_ready_without_a_configured_model()
    {
        LlmAppSettings settings = LlmAppSettings.Default()
            .WithProvider(new LlmProviderAppSettings("deepseek", "DeepSeek", "", ""));

        IReadOnlyList<LlmProviderReadiness> readiness =
            await LlmProviderClientFactory.InspectAsync(settings, new StubCredentialStore { Secret = "key" });

        LlmProviderReadiness deepseek = readiness.Single(item => item.ProviderId == "deepseek");
        deepseek.IsConfigured.Should().BeTrue("card readiness is credential + endpoint, not a model");
        deepseek.HasModel.Should().BeFalse();
        deepseek.Diagnostic.Should().Be("Ready.");
    }

