    [Fact]
    public void Normalize_stays_sparse_and_repairs_unknown_selections()
    {
        LlmAppSettings sparse = new([], "not-a-provider", "", "nope", "");

        LlmAppSettings normalized = sparse.Normalize();

        normalized.Providers.Should().BeEmpty("normalize never invents provider rows");
        normalized.OcrProviderId.Should().Be(LlmAppSettings.DefaultProviderId);
        normalized.ChatProviderId.Should().Be(LlmAppSettings.DefaultProviderId);
    }

    [Fact]
    public void Normalize_preserves_every_supplied_record_including_legacy_default_rows()
    {
        LlmProviderAppSettings[] legacyDefaults =
        [
            LlmProviderAppSettings.FromCatalog(LlmProviderCatalog.Find("openai")!) with
            {
                BaseUrl = "https://api.openai.com", Model = "gpt-4o-mini"
            },
            LlmProviderAppSettings.FromCatalog(LlmProviderCatalog.Find("anthropic")!) with
            {
                BaseUrl = "https://api.anthropic.com"
            },
            LlmProviderAppSettings.FromCatalog(LlmProviderCatalog.Find("deepseek")!)
        ];
        LlmProviderAppSettings configured = new("future-provider", "Future", "https://future.example", "m");
        LlmProviderAppSettings legacyAdded =
            LlmProviderAppSettings.FromCatalog(LlmProviderCatalog.Find("azure-openai")!) with
            {
                IsAdded = true
            };
        LlmAppSettings sparse = new([..legacyDefaults, configured, legacyAdded], "", "", "", "");

        LlmAppSettings normalized = sparse.Normalize();

        string[] expectedOrder = legacyDefaults
            .OrderBy(row => LlmProviderCatalog.CatalogOrder(row.ProviderId))
            .Select(row => row.ProviderId)
            .Concat(["future-provider", "azure-openai"])
            .ToArray();
        normalized.Providers.Select(provider => provider.ProviderId).Should()
            .Equal(expectedOrder, "supplied rows are never pruned, only reordered");
        LlmProviderAppSettings openAi = normalized.FindProvider("openai")!;
        openAi.BaseUrl.Should().Be("https://api.openai.com",
            "a legacy connection's saved endpoint is user-visible state, not autogenerated noise");
        openAi.Model.Should().Be("gpt-4o-mini");
        normalized.FindProvider("azure-openai")!.IsAdded.Should().BeTrue();
    }

    [Fact]
    public void Normalize_dedups_case_insensitively_and_keeps_configured_rows()
    {
        LlmAppSettings settings = LlmAppSettings.Default() with
        {
            Providers =
            [
                new LlmProviderAppSettings("anthropic", "Anthropic", "https://proxy.example", "claude-x"),
                new LlmProviderAppSettings("ANTHROPIC", "Anthropic", "https://other.example", "claude-y"),
                new LlmProviderAppSettings("deepseek", "DeepSeek", "", "deepseek-chat")
            ],
            OcrProviderId = "anthropic",
            OcrModel = ""
        };

        LlmAppSettings normalized = settings.Normalize();

        normalized.Providers.Select(provider => provider.ProviderId).Should()
            .Equal(new[] { "anthropic", "deepseek" }, "catalog order is deterministic");
        normalized.FindProvider("anthropic")!.BaseUrl.Should().Be("https://proxy.example");
        normalized.OcrSelection.Should().Be(("anthropic", "claude-x"));
    }

    [Fact]
    public void With_provider_replaces_a_row_without_duplicates_and_keeps_unrelated_records()
    {
        LlmAppSettings settings = LlmAppSettings.Default()
            .WithProvider(new LlmProviderAppSettings("deepseek", "", "", "deepseek-chat"))
            .WithProvider(new LlmProviderAppSettings("future-provider", "Future", "https://future.example", "m"))
            .WithProvider(new LlmProviderAppSettings("DEEPSEEK", "", "", "deepseek-reasoner"));

        settings.Providers.Should().HaveCount(2);
        settings.FindProvider("deepseek")!.Model.Should().Be("deepseek-reasoner");
        settings.FindProvider("DEEPSEEK")!.Model.Should().Be("deepseek-reasoner");
        settings.FindProvider("future-provider")!.BaseUrl.Should().Be("https://future.example");
        settings.Providers[0].ProviderId.Should().Be("DEEPSEEK",
            "catalog providers order by catalog position before non-catalog rows");
    }

    [Fact]
    public void Without_provider_removes_the_row_without_touching_others()
    {
        LlmAppSettings settings = LlmAppSettings.Default()
